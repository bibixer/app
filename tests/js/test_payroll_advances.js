// Run: gjs tests/js/test_payroll_advances.js
const Gio=imports.gi.Gio, ByteArray=imports.byteArray;
const source=ByteArray.toString(Gio.File.new_for_path('static/js/payroll-advances.js').load_contents(null)[1]);
const assert=(value,message)=>{if(!value)throw new Error(message);};
const element=()=>({checked:false,listeners:{},addEventListener(name,fn){this.listeners[name]=fn;}});
const all=element(), a=element(), b=element();
all.form={querySelectorAll:()=>[a,b]};
new Function('document',source)({getElementById:id=>id==='selectAllAdvances'?all:null});
assert(!all.checked&&!all.indeterminate,'None initially selected');
a.checked=true; a.listeners.change();
assert(!all.checked&&all.indeterminate,'Single selection marks select-all partial');
all.checked=true; all.listeners.change();
assert(a.checked&&b.checked&&all.checked&&!all.indeterminate,'Select all ticks every amount');
all.checked=false; all.listeners.change();
assert(!a.checked&&!b.checked&&!all.indeterminate,'Untick all clears every amount');
new Function('document',source)({getElementById:()=>null});
const jobs=element(), eligible=element(), selected=element(), blocked=element();
selected.checked=true;blocked.disabled=true;
jobs.form={querySelectorAll:()=>[eligible,selected,blocked]};
new Function('document',source)({getElementById:id=>id==='selectAllJobs'?jobs:null});
assert(jobs.indeterminate&&!jobs.checked,'Initially selected jobs set partial state');
jobs.checked=true;jobs.listeners.change();
assert(eligible.checked&&selected.checked&&!blocked.checked,'Select all jobs skips missing-rate disabled rows');
eligible.checked=false;eligible.listeners.change();
assert(jobs.indeterminate&&!jobs.checked,'Individual job changes update header');
jobs.checked=false;jobs.listeners.change();
assert(!eligible.checked&&!selected.checked&&!blocked.checked,'Untick all jobs clears eligible rows only');
const empty=element();empty.form={querySelectorAll:()=>[blocked]};
new Function('document',source)({getElementById:id=>id==='selectAllJobs'?empty:null});
assert(empty.disabled&&!empty.checked&&!empty.indeterminate,'All-ineligible or empty job list disables select all');
print('PASS: individual amount ticks, select all, clear all, partial and empty state');
